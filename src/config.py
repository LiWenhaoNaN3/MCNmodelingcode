def set_site(name):
    """切换海域; 同时设置数据文件后缀 (SITE_TAG)。"""
    global SITE, SITE_TAG
    if name not in SITES:
        raise KeyError("未知海域: %r (可选: %s)" % (name, list(SITES)))
    SITE.clear()
    SITE.update(SITES[name])
    SITE_TAG = None if name == "med" else name
    return SITE

